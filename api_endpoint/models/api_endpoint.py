# -*- coding: utf-8 -*-

import logging
from odoo import models, tools, fields, api, _

_logger = logging.getLogger(__name__)


class ApiEndpoint(models.Model):
    _name = 'api.endpoint'
    _description = 'API Endpoint'
    _inherit = ['mail.thread']

    name = fields.Char(
        required=True,
        tracking=True,
    )

    directon = fields.Selection(
        selection=[
            ('outbound', 'Outbound'),
            ('inbound', 'Inbound'),
        ],
        required=True,
        tracking=True,
        default='outbound',
    )

    role = fields.Selection(
        selection=[
            ('active', 'Active'),
            ('passive', 'Passive'),
        ],
        required=True,
        tracking=True,
        default='active',
    )

    comm_method = fields.Selection(
        selection=[
            ('get', 'HTTP GET'),
            ('post', 'HTTP POST'),
            ('delete', 'HTTP DELETE'),
            ('put', 'HTTP PUT'),
            ('xmlrpc', 'XML-RPC'),
            ('jsonrpc', 'JSON-RPC'),
            ('sftp', 'SFTP'),
        ],
        required=True,
        tracking=True,
        default='get',
    )

    file_format = fields.Char(
        selection=[
            ('json', 'JSON'),
            ('xml', 'XML'),
            ('csv', 'CSV'),
            ('zip', 'ZIP'),
        ],
        required=True,
        tracking=True,
        default='json',
    )

    sequence_id = fields.Many2one(
        comodel_name='ir.sequence',
        required=True,
        tracking=True,
        ondelete='restrict',
    )

    authorization = fields.Char(
        required=True,
        tracking=True,
        default='',
    )

    location = fields.Char(
        required=True,
        tracking=True,
        default='',
    )

    producer = fields.Text(
        tracking=True,
        help="Produces a new message. The output will be passed to processor.",
    )

    processor = fields.Text(
        tracking=True,
        help="Processes an message generated by the producer. The result will be imported to Odoo or send to an external system.",
    )


